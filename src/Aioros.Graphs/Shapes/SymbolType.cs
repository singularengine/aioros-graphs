namespace Aioros.Graphs.Shapes;

/// <summary>The symbol types of d3-shape.</summary>
public enum SymbolType
{
    /// <summary>A circle: <c>symbolCircle</c>.</summary>
    Circle,

    /// <summary>A Greek cross with arms of equal length: <c>symbolCross</c>.</summary>
    Cross,

    /// <summary>A rhombus: <c>symbolDiamond</c>.</summary>
    Diamond,

    /// <summary>An axis-aligned square: <c>symbolSquare</c>.</summary>
    Square,

    /// <summary>A pentagonal star: <c>symbolStar</c>.</summary>
    Star,

    /// <summary>An up-pointing triangle: <c>symbolTriangle</c>.</summary>
    Triangle,

    /// <summary>A Y shape: <c>symbolWye</c>.</summary>
    Wye,

    /// <summary>A plus sign, for stroking: <c>symbolPlus</c>.</summary>
    Plus,

    /// <summary>An X, for stroking: <c>symbolTimes</c> (<c>symbolX</c>).</summary>
    Times,

    /// <summary>An up-pointing triangle, for stroking: <c>symbolTriangle2</c>.</summary>
    Triangle2,

    /// <summary>An asterisk, for stroking: <c>symbolAsterisk</c>.</summary>
    Asterisk,

    /// <summary>A square, for stroking: <c>symbolSquare2</c>.</summary>
    Square2,

    /// <summary>A rotated square, for stroking: <c>symbolDiamond2</c>.</summary>
    Diamond2,
}
